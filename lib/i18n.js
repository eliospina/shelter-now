// How to name a shelter in a sentence: its street address when Lantmäteriet
// has one nearby, otherwise its property designation, named as a property
// (e.g. "property Hinken 1") so it isn't mistaken for a street.
export function placeName(lang, shelter) {
  return shelter.street ?? UI[lang].propertyRef.replace("{x}", shelter.address);
}

